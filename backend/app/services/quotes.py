def quote_for(day: date | None = None) -> str:
    """عبارة اليوم: ثابتة خلال اليوم الواحد ومتغيّرة بين الأيام."""
    day = day or date.today()
    return QUOTES[day.timetuple().tm_yday % len(QUOTES)]
